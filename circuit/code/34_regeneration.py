"""Is the mid-block damage STORED or REGENERATED?

Patching the full nctx residual at END at a single mid-block layer finds ~0 recovery, which
would suggest the mid-block is undamaged. 31_window_restore instead suppresses
mid-block sublayer *writes* at END across a window and recovers 51-72%. Both can hold only if the
damage is continuously re-generated by attention re-reading the context at higher layers: a
one-layer snapshot is immediately rebuilt, while sustained suppression is not.

This runs all three interventions on the same data:

  point:L    resid_post[END, L] <- nctx value            (single-layer residual patch, swept over L)
  prefix:L   restore attn_out+mlp_out at END for l < L   (no context written at END below L)
  suffix:L   restore attn_out+mlp_out at END for l >= L  (no context written at END from L up)

If the damage is stored at depth L, point:L recovers it. If it is regenerated above L, point:L
recovers ~0 while suffix:L recovers a lot. prefix:L is the complement: it says how much of the
damage the block below L is responsible for, given the block above still runs freely.
"""
import argparse, json, sys
from pathlib import Path
from collections import defaultdict
sys.path.insert(0, str(Path(__file__).parent))
import torch
from common import load

ROOT = Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser()
ap.add_argument("--model", required=True); ap.add_argument("--device", default="cuda:0")
ap.add_argument("--limit", type=int, default=60)
ap.add_argument("--conds", default="far_irr,long_irr")
a = ap.parse_args()
m = load(a.model, a.device); nL = m.cfg.n_layers
S = json.load((ROOT / "data" / "pairs_v1.json").open())["samples"][: a.limit]
CONDS = a.conds.split(",")

def fid(w):
    i = m.tokenizer.encode(" " + str(w), add_special_tokens=False); return i[0] if i else None

def readout(logits, gid):
    lg = logits[0, -1].float(); gold = float(lg[gid])
    o = lg.clone(); o[gid] = -1e9
    return gold, gold - float(o.max())

def mk(src):
    def hk(x, hook):
        x[:, -1, :] = src
        return x
    return hk

res = defaultdict(lambda: defaultdict(list))
with torch.no_grad():
    for s in S:
        gid = fid(s["gold"])
        if gid is None: continue
        ln, cn = m.run_with_cache(m.to_tokens(s["query"]))
        a_n = {L: cn["attn_out", L][0, -1].clone() for L in range(nL)}
        m_n = {L: cn["mlp_out", L][0, -1].clone() for L in range(nL)}
        r_n = {L: cn["resid_post", L][0, -1].clone() for L in range(nL)}
        del cn
        gn = readout(ln, gid)
        for cond in CONDS:
            v = s["variants"].get(cond, [])
            if not v: continue
            tc = m.to_tokens(f"{v[0]['context']} {s['query']}")
            res[cond]["_nctx"].append(gn); res[cond]["_ctx"].append(readout(m(tc), gid))
            for L in range(nL):
                res[cond][f"point:{L}"].append(readout(
                    m.run_with_hooks(tc, fwd_hooks=[(f"blocks.{L}.hook_resid_post", mk(r_n[L]))]), gid))
                pre = [(f"blocks.{l}.hook_{p}_out", mk((a_n if p == "attn" else m_n)[l]))
                       for l in range(L) for p in ("attn", "mlp")]
                res[cond][f"prefix:{L}"].append(readout(m.run_with_hooks(tc, fwd_hooks=pre), gid))
                suf = [(f"blocks.{l}.hook_{p}_out", mk((a_n if p == "attn" else m_n)[l]))
                       for l in range(L, nL) for p in ("attn", "mlp")]
                res[cond][f"suffix:{L}"].append(readout(m.run_with_hooks(tc, fwd_hooks=suf), gid))

def mn(xs, i): return sum(x[i] for x in xs) / len(xs)

print(f"\n=== {a.model}: is the damage stored or regenerated?  n={a.limit} ===")
out = {}
for cond in CONDS:
    if not res[cond]["_ctx"]: continue
    gc, mc = mn(res[cond]["_ctx"], 0), mn(res[cond]["_ctx"], 1)
    gN, mN = mn(res[cond]["_nctx"], 0), mn(res[cond]["_nctx"], 1)
    print(f"\n  --- {cond} ---  damage: gold {gc-gN:+.3f}  margin {mc-mN:+.3f}")
    print(f"  {'depth':>6s} {'point=L':>12s} {'prefix<L':>10s} {'suffix>=L':>10s}   (gold-logit recovery)")
    for L in range(0, nL, max(1, nL // 12)):
        row = []
        for kind in ("point", "prefix", "suffix"):
            g = mn(res[cond][f"{kind}:{L}"], 0)
            row.append((g - gc) / (gN - gc) if abs(gN - gc) > 1e-6 else float("nan"))
        print(f"  {100*L/nL:5.0f}% {100*row[0]:11.1f}% {100*row[1]:9.1f}% {100*row[2]:9.1f}%")
    for L in range(nL):
        for kind in ("point", "prefix", "suffix"):
            g, mg = mn(res[cond][f"{kind}:{L}"], 0), mn(res[cond][f"{kind}:{L}"], 1)
            out[f"{cond}|{kind}:{L}"] = dict(
                gold=g, margin=mg,
                recov_gold=(g - gc) / (gN - gc) if abs(gN - gc) > 1e-6 else None,
                recov_margin=(mg - mc) / (mN - mc) if abs(mN - mc) > 1e-6 else None)
    out[f"{cond}|_ctx"] = dict(gold=gc, margin=mc); out[f"{cond}|_nctx"] = dict(gold=gN, margin=mN)
json.dump(out, (ROOT / "results" / f"regen_{a.model}.json").open("w"), indent=1)
